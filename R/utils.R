#' Null-coalescing operator: `y` when `x` is `NULL`, else `x`.
#'
#' Defined here rather than imported so the package keeps working on the
#' oldest supported R, where base does not export it.
#'
#' @noRd
`%||%` <- function(x, y) if (is.null(x)) y else x

# --- argument checks shared by the whole export surface ---------------
#
# These exist because the idioms they replace fail SILENTLY. `isTRUE(x)`
# reads a length-2 logical, a string, an integer and `NA` all as FALSE,
# so a flag set by mistake used to fit the OTHER model and report it as
# the user's. A length-2 `level` recycles against the parameter vector
# and puts DIFFERENT coverages on different rows of one table, with no
# column heading to record it. Each check turns one of those into a
# refusal that names the argument and says what it had to be.
#
# Every check raises exactly one message, so the whole family adds a
# handful of condition messages rather than one per call site, and the
# argument name that varies at run time comes from the caller.

#' What a rejected argument actually was, as a phrase a message can end
#' with. Deliberately short: the caller's message has already said what
#' the argument had to be, so this only has to identify what arrived.
#'
#' @noRd
arg_desc <- function(x) {
  if (is.null(x)) return("NULL")
  cls <- class(x)[1L]
  if (is.atomic(x) && length(x) == 1L) {
    if (is.na(x)) return(paste0(cls, " NA"))
    return(paste0(cls, " ", encodeString(format(x), quote = "\"")))
  }
  art <- if (substr(cls, 1L, 1L) %in% c("a", "e", "i", "o", "u")) "an" else "a"
  paste0(art, " ", cls, " of length ", length(x))
}

# --- refusing an argument that fell into `...` ------------------------
#
# A method whose `...` is never read accepts EVERY name, so a misspelled
# argument and an unsupported one both change nothing and say nothing.
# That is how `fitted(fit, re_formula = NA)` returned the conditional
# fit: 1.291651 at the first row of the fixture in
# tests/testthat/test-arg-refusal.R, identical to `fitted(fit)`, where
# the population answer is 1.954262, measured by dev/argspell-defect.R
# against frmtmb 0.57.0. Refusing the dots is what stops the
# class rather than that one instance, because a swallowing method takes
# every argument brms adds in future the same way.
#
# The refusal is NOT applied to a method of a generic another package
# owns and calls itself (emmeans, insight, marginaleffects): those
# callers pass arguments of their own choosing, so accepting them is the
# contract. `dev/argspell-findings.md` lists the exclusions by name.

# --- what R's S3 contract obliges a method to tolerate ------------
#
# The refusal's rule was "refuse what the METHOD does not have". R's S3
# contract is different: a method must tolerate the arguments its
# GENERIC is documented to carry, which is why every `stats` default
# method declares `use.fallback`, `env`, `data`, `na.rm` or `trace` and
# then ignores them. The two rules collide wherever base R hands a model
# to a generic with an extra name, and three rounds of one-off `.allow`
# patches each uncovered the next hop: `nobs(use.fallback =)` from
# `step()`, then `drop1(scale =, trace =)` from the same call, then
# `formula(env =)` from `as.formula()`, then `terms(data =)` from
# `model.matrix.default()` and four more.
#
# One table, consulted by `frm_check_dots()` for every method at once.
# `dev/argspell-contract.R` derives it by walking the ASTs of R's own
# packages for calls to these generics, and
# `tests/testthat/test-arg-refusal.R` runs the same scan and fails if a
# name turns up that is not here, so the NEXT hop is found by the suite
# rather than by a user.
#
# Everything not named here is still refused: `drop1(fit, re.form = NA)`
# and `nobs(fit, nosucharg = 1)` error as before, and an `.unsupported`
# entry still wins, so `print(fit, digits = 3)` keeps its reason.

