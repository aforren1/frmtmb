#' The display name of the function that called the checker.
#'
#' A method reached through `UseMethod()` reports its own name, so
#' `fitted.frmtmb_fit` has to be cut back to `fitted()`: the caller
#' typed the generic, and a message naming the method sends them looking
#' for a function they never wrote. `print.summary.frmtmb_fit` is the
#' case that needs the optional `summary.` in the pattern; without it
#' the message named `print.summary()`, which is not a function.
#'
#' @noRd
calling_fun_name <- function(which) {
  nm <- tryCatch(deparse(sys.call(which)[[1L]]), error = function(e) NA)
  if (length(nm) != 1L || is.na(nm)) return(NA_character_)
  sub(paste0("[.](summary[.])?",
             "(frmtmb|ranef_frmtmb|VarCorr_frmtmb|default)",
             "[.A-Za-z0-9_]*$"),
      "", nm)
}

#' The formal this caller most likely meant, or `NULL`.
#'
#' A single-edit typo is worth naming; anything further apart is a guess
#' dressed as help, so the threshold grows with the name's length.
#'
#' @noRd
nearest_formal <- function(bad, known) {
  known <- setdiff(known, "...")
  if (!length(known) || !nzchar(bad)) return(NULL)
  d <- utils::adist(bad, known, ignore.case = TRUE)[1L, ]
  i <- which.min(d)
  if (d[i] > max(1L, floor(nchar(bad) / 4))) return(NULL)
  known[i]
}

#' Refuse every argument that landed in `...`.
#'
#' Called as `frm_check_dots(...)` from a method that does not read its
#' dots. The function's own name and formals come from the calling
#' frame, so the call site is the same one line everywhere and cannot
#' drift out of step with a renamed argument.
#'
#' @param ... The caller's dots, forwarded.
#' @param .unsupported Named character vector: argument name to the
#'   reason it is refused. Use it for an argument that is REAL in brms
#'   and simply cannot be honored here, so that the refusal says why
#'   instead of reporting the name as unknown.
#' @param .allow Character vector of names this call really does
#'   forward, for a method that passes its dots on from ONE branch, or
#'   `TRUE` for a method that forwards ALL of them to a function with
#'   dots of its own. `.unsupported` is checked first either way, so a
#'   retired spelling is still refused by a method that forwards.
#' @noRd
frm_check_dots <- function(..., .unsupported = NULL, .allow = NULL) {
  n <- ...length()
  if (n == 0L) return(invisible(NULL))
  w <- sys.parent()
  gen <- calling_fun_name(w)
  what <- if (is.na(gen)) "this function" else paste0(gen, "()")
  known <- tryCatch(names(formals(sys.function(w))), error = function(e) NULL)
  # what R's own machinery passes through this generic, which a method
  # has to tolerate whatever its own formals say
  contract <- if (!is.na(gen)) s3_contract_args[[gen]]
  nms <- ...names()
  if (is.null(nms)) nms <- rep("", n)
  nms[is.na(nms)] <- ""
  bad <- nms[nzchar(nms)]
  # first, and before the catch-all below: a name that was a real
  # spelling of a real setting until the rename has to be refused even
  # by a method that forwards its dots, or it goes on meaning nothing
  hit <- intersect(bad, names(.unsupported))
  if (length(hit)) {
    stop(what, " cannot honor `", hit[1L], "`: ", .unsupported[[hit[1L]]],
         call. = FALSE)
  }
  if (isTRUE(.allow)) return(invisible(NULL))
  bad <- setdiff(bad, contract)
  unnamed <- sum(!nzchar(nms))
  if (unnamed > 0L) {
    stop(what, " was given ", unnamed, " argument",
         if (unnamed > 1L) "s" else "", " with no name, which it has ",
         "nowhere to put. It takes: ",
         paste(setdiff(known, "..."), collapse = ", "), call. = FALSE)
  }
  bad <- setdiff(bad, .allow)
  if (!length(bad)) return(invisible(NULL))
  # the nearest name is looked for among everything the call really
  # accepts, but only the method's OWN arguments are listed back: for
  # `plot()` the contract is 95 graphical parameters and printing them
  # would bury the answer
  guess <- nearest_formal(bad[1L], c(known, .allow, contract))
  stop(what, " has no argument `", bad[1L], "`",
       if (length(bad) > 1L) {
         paste0(" (and ", length(bad) - 1L, " more: ",
                paste(bad[-1L], collapse = ", "), ")")
       } else "",
       if (is.null(guess)) "" else paste0(". Did you mean `", guess, "`?"),
       ". It takes: ",
       paste(setdiff(c(known, .allow), "..."), collapse = ", "),
       call. = FALSE)
}

# --- one setting under two spellings ----------------------------------
#
# The naming rule: brms is the TIEBREAKER. Where lme4 or glmmTMB and
# brms disagree on a name, the brms spelling is the one this package
# takes and the lme4 one is DROPPED, not deprecated.
# `predict()` and `simulate()` therefore take `re_formula` and no longer
# take `re.form`, and `predict()` no longer accepts `allow.new.levels`.
#
# Two spellings of one setting survive in exactly one place: where brms
# ITSELF carries both. `posterior_epred.brmsfit()` and
# `posterior_predict.brmsfit()` take `re_formula` and `re.form` side by
# side, so the frmtmb.sample methods of those generics do too. That is
# matching brms, not preserving history. Supplying both at once is
# refused rather than resolved: two names for one setting given together
# is a question about what the caller meant, not a preference to guess
# at.

#' The "argument was not supplied" marker for a dual-spelled argument.
#'
#' A sentinel is needed rather than a plain default because `NULL` and
#' `NA` are both REAL settings for a random-effect formula (keep the
#' random effects; drop them), so neither can double as "unset". Its
#' class is the whole implementation: nothing a caller can pass carries
#' it.
#'
#' @noRd
arg_unset <- function() structure(list(), class = "frmtmb_arg_unset")

#' @noRd
is_arg_unset <- function(x) inherits(x, "frmtmb_arg_unset")

#' One value out of two spellings of one argument.
#'
#' `primary` is the spelling the function is named after (brms's),
#' `alias` the accepted historical one; `default` is what the function
#' does when neither is given, which is by construction the default it
#' had before the alias existed.
#'
#' @noRd
dual_arg <- function(primary, alias, primary_name, alias_name, what,
                     default = NULL) {
  set_primary <- !is_arg_unset(primary)
  set_alias <- !is_arg_unset(alias)
  if (set_primary && set_alias) {
    stop(what, " was given both `", primary_name, "` and `", alias_name,
         "`, which are two spellings of ONE setting, so it cannot tell ",
         "which was meant. `", primary_name, "` is the spelling this ",
         "function takes (it is brms's, and this is a brms function); `",
         alias_name, "` is accepted as an alias. Pass one of them",
         call. = FALSE)
  }
  if (set_primary) return(primary)
  if (set_alias) return(alias)
  default
}

#' The random-effect formula of a brms-named draws method, from either
#' spelling. Kept as its own wrapper so that every call site names the
#' same two spellings and only the function name and the default vary.
#'
#' @noRd
re_form_arg <- function(re_formula, re.form, what, default = NULL) {
  dual_arg(re_formula, re.form, "re_formula", "re.form", what,
           default = default)
}

#' The one refusal every TRUE/FALSE argument in the package shares.
#'
#' @noRd
check_flag <- function(x, arg, what = NULL) {
  if (!is.logical(x) || length(x) != 1L || is.na(x)) {
    stop("`", arg, "` must be TRUE or FALSE, not ", arg_desc(x),
         if (is.null(what)) "" else paste0(". ", what), call. = FALSE)
  }
  invisible(x)
}

#' A single whole number at or above `min`: counts of draws, restarts
#' and grid points. A length-2 or fractional count otherwise reaches
#' `seq_len()` or `numeric()` as a size, where the message names neither
#' the argument nor the function the user called.
#'
#' @noRd
check_count <- function(x, arg, min = 0L) {
  ok <- is.numeric(x) && length(x) == 1L && is.finite(x) &&
    x == round(x) && x >= min
  if (!ok) {
    stop("`", arg, "` must be a single whole number of at least ", min,
         ", not ", arg_desc(x), call. = FALSE)
  }
  invisible(as.integer(x))
}

#' A single number strictly inside (0, 1): every coverage argument
#' (`level`, `prob`).
#'
#' @noRd
check_probability <- function(x, arg) {
  if (!is.numeric(x) || length(x) != 1L || !is.finite(x) ||
        x <= 0 || x >= 1) {
    stop("`", arg, "` must be a single number strictly between 0 and 1, ",
         "not ", arg_desc(x), call. = FALSE)
  }
  invisible(as.numeric(x))
}

