# Builds dev/codesize-findings.md from dev/codesize-findings-src.md: each
# line `<!-- BLOCK name -->` is replaced by the lines between
# "BEGIN name" and "END name" of dev/codesize-<name>.log, so every number
# in a block comes from the script that made it.
#   Rscript dev/codesize-assemble.R
d <- "C:/Users/adf44/source/r/frmtmb-wt-codesize/dev"
src <- readLines(file.path(d, "codesize-findings-src.md"), warn = FALSE)
res <- character()
for (l in src) {
  m <- regmatches(l, regexec("^<!-- BLOCK ([a-z-]+) -->$", l))[[1]]
  if (!length(m)) { res <- c(res, l); next }
  nm <- m[2]
  lg <- readLines(file.path(d, paste0(nm, ".log")), warn = FALSE)
  b <- grep(paste0("^BEGIN ", nm, "$"), lg); e <- grep(paste0("^END ", nm, "$"), lg)
  stopifnot(length(b) == 1, length(e) == 1, e > b)
  res <- c(res, paste0("Generated by `dev/", nm, ".R` (log `dev/", nm,
                       ".log`):"), "", "```", lg[(b + 1):(e - 1)], "```")
}
writeLines(res, file.path(d, "codesize-findings.md"))
cat("wrote", length(res), "lines\n")
