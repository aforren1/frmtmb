# The reach of each defect: the summed pair weight (weights.tsv, the
# product of the two features' weights) of the feature pairs the defect
# covers, not only the pair the sample drew. A defect covers the pairs
# it was MEASURED on, or that its repro script ran; a wider class it
# probably reaches is named in the findings, not counted here.
#
#   Rscript dev/equiv-reach.R [--record]
#
# --record writes the table into the findings between its markers.
w <- read.delim("dev/equiv-data/weights.tsv", stringsAsFactors = FALSE)
wt <- stats::setNames(w$weight, w$feature)
reach <- function(a, b) sum(outer(wt[a], wt[b]))
# a feature name such as |ID| would end a markdown cell
cell <- function(x) gsub("|", "\\|", x, fixed = TRUE)
defects <- list(
  list(id = "D1", pairs = "p049, nl sweep",
       what = "nl = TRUE with an ordinal family drops the nonlinear body",
       a = "nl", b = c("cumulative", "sratio", "cratio", "acat",
                      "hurdle_cumulative"), how = "silent"),
  list(id = "D2", pairs = "p043",
       what = "brms's class = \"sds\" is refused; alias it to class sd",
       a = "s()", b = "prior", how = "loud, remedy named"),
  list(id = "D3", pairs = "p124, p069",
       what = "importance = stops with \"did not converge\"",
       a = "importance", b = c("binomial", "poisson"), how = "loud"),
  list(id = "D4", pairs = "p013",
       what = "frm_curve() and frm_linpred() drop the cs() offsets",
       a = "cs_pred()", b = "frm_curve", how = "silent"),
  list(id = "D5", pairs = "p070, p087",
       what = "mm() with an |ID| key, or with cov = A, is refused",
       a = "mmc()", b = c("|ID|", "gr_cov"), how = "loud"),
  list(id = "D6", pairs = "p167",
       what = "arma(cov = TRUE) on a poisson response is refused",
       a = "arma()", b = "poisson", how = "loud"),
  list(id = "D7", pairs = "p158",
       what = "bf(nl = TRUE, autocor = ~ fcor(M)) is refused",
       a = "fcor()", b = "nl", how = "loud"),
  list(id = "D8", pairs = "p169",
       what = "an mi() response under von_mises is refused",
       a = "mi()", b = "von_mises", how = "loud"))
out <- c("<!-- generated by dev/equiv-reach.R; do not edit -->", "",
         "| defect | pairs | what | covers | reach | kind |",
         "|---|---|---|---|---|---|")
for (d in defects) {
  out <- c(out, sprintf("| %s | %s | %s | %s x %s | %.0f | %s |", d$id,
                        d$pairs, cell(d$what),
                        cell(paste(d$a, collapse = ", ")),
                        cell(paste(d$b, collapse = ", ")), reach(d$a, d$b),
                        d$how))
}
cat(out, sep = "\n")
if ("--record" %in% commandArgs(trailingOnly = TRUE)) {
  fp <- "dev/equiv-findings.md"
  fx <- readLines(fp, warn = FALSE)
  b <- grep("^<!-- equiv-reach begin -->$", fx)
  e <- grep("^<!-- equiv-reach end -->$", fx)
  if (length(b) == 1L && length(e) == 1L && e > b) {
    writeLines(c(fx[seq_len(b)], out, fx[e:length(fx)]), fp)
  }
}
