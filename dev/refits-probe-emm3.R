source("dev/refits-lib.R")
set.seed(6)
dj <- data.frame(x = rnorm(50), f = factor(rep(c("a", "b"), 25)))
dj$y <- 1 + dj$x + rnorm(50)
fj <- frm(y ~ x + f, data = dj)
r <- frmtmb:::recover_data.frmtmb_fit(fj, dpar = "nope")
print(class(r))
print(unclass(r)[1])
print(class(attr(r, "condition")))
print(r$message)
print(conditionMessage(r))
e <- tryCatch(stop(r), error = function(e) e)
print(class(e))
print(conditionMessage(e))
print(body(emmeans::ref_grid)[[1]])
f <- deparse(emmeans::ref_grid)
cat(f[18:40], sep = "\n")
