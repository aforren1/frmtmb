#!/usr/bin/env bash
# The equivalence survey, end to end, in one command:
#
#   bash dev/equiv-run.sh [jobs] [outdir]
#
# from the worktree root. It measures every pair of
# dev/equiv-data/sample.tsv that has no result yet (resumable: delete a
# pair's .tsv, or pass FORCE=1, to remeasure it), one pair per R
# process, `jobs` at a time (default 8), then writes results.tsv,
# compat-proposals.tsv and summary.md into `outdir`. To measure another
# build, point FRMTMB_EQUIV_LIB at its library (default rellib-r15).
#
# The tracked record (dev/equiv-data/ and the generated blocks of
# dev/equiv-findings.md) changes only with RECORD=1, which also reruns
# the nl x family sweep into the record. Without it a rerun into any
# outdir leaves the record alone.
#
# Do not edit this file, or any script it runs, while it runs: bash reads
# a script as it goes, so an edit moves the offset it resumes from.
#
# Rtools goes at the END of PATH: first on PATH, its bash and its
# libraries make Rscript segfault or read the wrong library.
set -u
jobs=${1:-8}
out=${2:-dev/equiv-out}
R="/c/Program Files/R/R-4.6.1/bin/Rscript.exe"
rt=/c/rtools45
export PATH="$PATH:$rt/usr/bin:$rt/x86_64-w64-mingw32.static.posix/bin"
export R_MAKEVARS_USER="C:/Users/adf44/Documents/.R/Makevars.win"
export FRMTMB_STAN_CACHE="$(cd dev/stan-cache && pwd -W)"
export NOT_CRAN=true
mkdir -p "$out/logs"
force=""
if [ "${FORCE:-0}" = "1" ]; then force="--force"; fi
record=""
if [ "${RECORD:-0}" = "1" ]; then record="--record"; fi

ids=$(awk -F'\t' 'NR > 1 { gsub(/"/, "", $1); print $1 }' \
  dev/equiv-data/sample.tsv)
start=$(date +%s)
printf '%s\n' $ids | xargs -P "$jobs" -I{} bash -c \
  "timeout 2400 \"$R\" dev/equiv-measure.R {} \"$out\" $force \
     > \"$out/logs/{}.log\" 2>&1 ||
   echo \"FAILED {} exit \$?\" >> \"$out/logs/{}.log\""
end=$(date +%s)
echo "measured in $((end - start)) s"
if [ -n "$record" ]; then
  "$R" dev/equiv-nl-sweep.R --record > "$out/logs/nl-sweep.log" 2>&1
fi
"$R" dev/equiv-summary.R "$out" $record
"$R" dev/equiv-reach.R $record > /dev/null
