source("C:/Users/adf44/source/r/frmtmb-wt-latres/dev/review-latres-common.R")
set.seed(3)
d <- expand.grid(t = 1:10, g = factor(1:20))
d <- d[order(d$g, d$t), ]
d$x <- rnorm(nrow(d))
e <- as.vector(replicate(20, arima.sim(list(ar = 0.6), 10, sd = 0.5)))
d$y <- rpois(nrow(d), exp(0.5 + 0.3 * d$x + e))
fit <- frm(y ~ x + ar(t, g, cov = TRUE), family = poisson(), data = d)
print(fit$opt$convergence)
print(summary(fit))
print(rownames(vcov(fit, full = TRUE)))
print(confint_varcorr(fit))
print(summary(fit)$cor_pars)
print(confint(fit))
print(variables(fit))
print(fit$obj$fn(fit$obj$par))
print(fit$obj$fn(fit$opt$par))
print(fit$obj$par); print(fit$opt$par)
print(fixef(fit))
print(diagnose(fit))
