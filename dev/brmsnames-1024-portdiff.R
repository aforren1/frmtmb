## Which ported brms-suite rows flip between 0.74.0 and the lane, from
## the record-mode runs of dev/brmsnames-1024-port.sh.
##
##   Rscript dev/brmsnames-1024-portdiff.R > dev/brmsnames-1024-log/portdiff.md
##
## One row per assertion (kind "assert"), keyed by package and id, read
## as dev/brmsport-ledger.R reads it. A row flips when `held` differs
## between the arms; `msg` changes are listed separately, since a row
## can keep its outcome and change what it reports.
cols <- c("kind", "pkg", "id", "verdict", "held", "vacuous", "msg",
          "caught", "raw_held")
read_arm <- function(arm) {
  fs <- list.files(file.path("dev/brmsnames-1024-port-out", arm),
                   "^rec-.*[.]tsv$", full.names = TRUE)
  x <- do.call(rbind, lapply(fs, function(f) {
    utils::read.delim(f, header = FALSE, quote = "", col.names = cols,
                      colClasses = "character", na.strings = NULL)
  }))
  x <- x[x$kind == "assert", ]
  x$key <- paste(x$pkg, x$id)
  x
}
b <- read_arm("base")
l <- read_arm("lane")
cat("<!-- generated by dev/brmsnames-1024-portdiff.R -->\n\n")
libs <- function(arm) {
  fs <- list.files(file.path("dev/brmsnames-1024-port-out", arm),
                   "^run-.*[.]txt$", full.names = TRUE)
  unique(unlist(lapply(fs, function(f) grep("^lib", readLines(f),
                                            value = TRUE))))
}
cat("Library lines, base:", paste(libs("base"), collapse = "; "), "\n\n")
cat("Library lines, lane:", paste(libs("lane"), collapse = "; "), "\n\n")
cat("Assertions recorded: base", nrow(b), ", lane", nrow(l), "\n\n")
cat("Held: base", sum(b$held == "TRUE"), ", lane", sum(l$held == "TRUE"),
    "\n\n")
cat("On one arm only:", length(setdiff(b$key, l$key)) +
      length(setdiff(l$key, b$key)), "\n\n")
m <- merge(b, l, by = "key", suffixes = c(".base", ".lane"))
flip <- m[m$held.base != m$held.lane, ]
cat("Rows whose outcome flips:", nrow(flip), "\n\n")
if (nrow(flip)) {
  cat("| row | verdict | held, base | held, lane | message, lane |\n")
  cat("|---|---|---|---|---|\n")
  cat(sprintf("| %s | %s | %s | %s | %s |\n", flip$key, flip$verdict.base,
              flip$held.base, flip$held.lane,
              substr(gsub("[|\n]", " ", flip$msg.lane), 1, 160)), sep = "")
}
msg <- m[m$held.base == m$held.lane & m$msg.base != m$msg.lane, ]
cat("\nRows with the same outcome and another message:", nrow(msg), "\n\n")
if (nrow(msg)) {
  cat("| row | base | lane |\n|---|---|---|\n")
  cat(sprintf("| %s | %s | %s |\n", msg$key,
              substr(gsub("[|\n]", " ", msg$msg.base), 1, 140),
              substr(gsub("[|\n]", " ", msg$msg.lane), 1, 140)), sep = "")
}
