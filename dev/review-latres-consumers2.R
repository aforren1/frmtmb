show <- function(label, expr) {
  r <- msg_of(eval.parent(substitute(expr)))
  cat("---", label, "\n")
  if (!is.null(r$err)) cat("ERR:", substr(r$err, 1, 300), "\n") else {
    print(r$val)
  }
  if (length(r$warn)) cat("WARN:", substr(paste(r$warn, collapse = " | "), 1, 300), "\n")
  invisible(r$val)
}
