# Lane sampleprior: paste log lines into dev/sampleprior-findings.md
# between `<!-- <marker>:begin -->` and `<!-- <marker>:end -->`, as a
# fenced block, so a number in the findings is the log's and not typed.
#   Rscript dev/sampleprior-splice.R <marker> <regex> <log> [<log> ...]
a <- commandArgs(TRUE)
marker <- a[1]
pat <- a[2]
logs <- a[-(1:2)]
wt <- "C:/Users/adf44/source/r/frmtmb-wt-sampleprior"
lines <- unlist(lapply(logs, function(f) {
  x <- readLines(file.path(wt, f), warn = FALSE)
  x <- grep(pat, x, value = TRUE)
  if (length(logs) > 1L) paste0(basename(f), ": ", x) else x
}))
f <- file.path(wt, "dev/sampleprior-findings.md")
s <- readLines(f)
b <- grep(paste0("^<!-- ", marker, ":begin"), s)
e <- grep(paste0("^<!-- ", marker, ":end"), s)
stopifnot(length(b) == 1L, length(e) == 1L, e > b)
blk <- c(paste0("<!-- ", marker, ":begin (generated by ",
                "dev/sampleprior-splice.R from ",
                paste(logs, collapse = ", "), ") -->"),
         "```", lines, "```")
s <- c(s[seq_len(b - 1L)], blk, s[e:length(s)])
writeLines(s, f)
cat("spliced", length(lines), "lines into", marker, "\n")
