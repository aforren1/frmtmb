## An author writes a percent sign ESCAPED, as `\%`; an unescaped one
## starts a comment and silently swallows the rest of its line. So two
## numbers matter per file, and roxygen's own `%` header lines are not
## either of them.
counts <- function(src) {
  body <- src[!grepl("^%", src)]
  n <- function(re) sum(vapply(gregexpr(re, body, perl = TRUE),
                               function(m) sum(m > 0), 0L))
  c(escaped = n("\\\\%"), unescaped = n("(?<!\\\\)%"))
}
rendered_pct <- function(txt) {
  sum(vapply(gregexpr("%", txt, fixed = TRUE),
             function(m) sum(m > 0), 0L))
}

bad <- 0L
for (f in files) {
  p <- file.path(man, f)
  src <- readLines(p, warn = FALSE)
  out <- tempfile()
  tools::Rd2txt(p, out = out)
  txt <- readLines(out, warn = FALSE)
  k <- counts(src)
  got <- rendered_pct(txt)
  ok <- k[["unescaped"]] == 0L && got == k[["escaped"]]
  cat(sprintf("%-30s escaped=%d unescaped=%d rendered=%d  %s\n",
              f, k[["escaped"]], k[["unescaped"]], got,
              if (ok) "ok" else "DEFECT"))
  if (!ok) bad <- bad + 1L
}
cat("files with a dropped or unescaped percent sign: ", bad, "\n")

## Both inverse cases, so neither branch is unreachable. An UNESCAPED
## sign must be counted as such and must vanish from the render; an
## ESCAPED one must be counted as such and must survive it.
probe <- function(line) {
  tmp <- tempfile(fileext = ".Rd")
  writeLines(c("% Generated by roxygen2: do not edit by hand",
               "\\name{zz}", "\\alias{zz}", "\\title{zz}",
               paste0("\\description{", line, "}"),
               "\\keyword{internal}"), tmp)
  out <- tempfile()
  tools::Rd2txt(tmp, out = out)
  c(counts(readLines(tmp)),
    rendered = rendered_pct(readLines(out, warn = FALSE)))
}
