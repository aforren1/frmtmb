## generates, so a raw count of unescaped signs is 2 on a clean file and
## a summary line that fires on "greater than zero" is UNCONDITIONAL and
## says nothing. Those two header lines are excluded and the per-file
## count is the instrument: it moves to 1 on the first author `%`.
