# Why did the fix_h mutant change nothing? Trace the step and the slopes on the
# scale 1e5 Poisson, directly from imp_anchor_slopes()'s pieces.
source("C:/Users/adf44/source/r/frmtmb-wt-impsamp/dev/review-impsamp-common.R")
Sys.setenv(REV_MUTLIB = "C:/Users/adf44/source/r/rev-impsamp-lib/fix_h")
set_libs("mutant")
suppressPackageStartupMessages(library(frmtmb))
ns <- asNamespace("frmtmb")
cat("lib", find.package("frmtmb"), "\n")
b <- paste(deparse(body(ns$imp_anchor_slopes)), collapse = "\n")
cat("has djoint:", grepl("djoint", b), "\n")
set.seed(1)
G <- 15L
g <- factor(rep(seq_len(G), each = 10))
x <- rnorm(150)
u <- rnorm(G, 0, 0.8)
y <- rpois(150, exp(0.5 + 0.5 * x + u[g]))
d <- data.frame(y, xx = 1e5 * x, g)
fr <- frm(bf(y ~ xx + (1 | g)), family = poisson(), data = d, dry_run = "frame")
nll <- ns$build_objective(fr)
tpl <- ns$make_start(fr, NULL, NULL)
lap <- RTMB::MakeADFun(nll, tpl, random = "b", map = fr[["map"]], silent = TRUE)
opt <- suppressWarnings(nlminb(lap$par, lap$fn, lap$gr))
print(setNames(opt$par, names(lap$par)))
lap$fn(opt$par)
full <- lap$env$last.par
H <- lap$env$spHess(full, random = FALSE)
cat("class", class(H), "dim", dim(H), "\n")
rnd <- lap$env$random
fix <- setdiff(seq_along(full), rnd)
print(Matrix::diag(H)[fix])
print(1e-4 / sqrt(Matrix::diag(H)[fix]))
lay <- ns$imp_layout(fr[["re_blocks"]])
plan <- ns$imp_plan(lap, fr, lay, setNames(opt$par, names(lap$par)), 64L, 1L)
cat("rate range by coordinate:\n")
print(apply(plan$hlik_rate, 2, range))
cat("cross range by coordinate:\n")
print(apply(plan$cross_d, 2, range))
io <- ns$build_importance_objective(fr, lay, ns$imp_group_map(fr, lay), plan)
otpl <- ns$imp_template(tpl, "b")
obj <- RTMB::MakeADFun(io$fn, otpl, silent = TRUE)
print(obj$fn(opt$par))
print(obj$gr(opt$par))
# par_units the fit used
fit <- suppressWarnings(frm(bf(y ~ xx + (1 | g)), family = poisson(), data = d,
                            importance = 64L, verbose = TRUE))
print(fit$par_units)
print(fit$importance[c("rounds", "moves", "grads")])
print(fit$opt$message)
