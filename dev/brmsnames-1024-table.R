## The name table of dev/brmsnames-1024-findings.md, generated from the
## outputs of dev/brmsnames-1024-brms.R and dev/brmsnames-1024-frm.R.
##
##   Rscript dev/brmsnames-1024-table.R > dev/brmsnames-1024-log/table.md
##
## Table 1 lists fixef() names: brms 2.23.0, frmtmb 0.74.0 (rellib-r12)
## and the lane. Table 2 compares each interface with brms, per arm,
## written "base / lane":
##   ok     the same names in the same order
##   order  the same names in another order
##   DIFF   other names
##   n/a    neither package has the output (no group-level terms)
##   ERR    frmtmb could not fit the model
## Interfaces: fixef, vcov and summary row names; variables() (the
## b_, bs_, bsp_, bcs_, sd_, sds_ and cor_ names); default_prior() coef
## rows of the classes frmtmb has (b, Intercept, sd, simo); set_prior()
## with brms's spelling of each such row, through validate_prior();
## hypothesis() on every brms coefficient name; frm_sample() draws (the
## same names plus simo_); coef(), ranef() and VarCorr() term names;
## conditional_effects() effect names.
out <- "dev/brmsnames-1024-out"
P <- "^(b|bs|bsp|bcs|sds|sd|cor)_"
PD <- "^(b|bs|bsp|bcs|sds|sd|cor|simo)_"
refused <- c("sds", "meanme", "sdme")
n <- length(list.files(out, "^brms-"))
`%||%` <- function(a, b) if (is.null(a)) b else a
cmp <- function(a, b) {
  if (is.character(a) && length(a) == 1L && startsWith(a, "ERROR")) {
    a <- character(0)
  }
  if (is.character(b) && length(b) == 1L && startsWith(b, "ERROR")) {
    b <- character(0)
  }
  a <- unname(unlist(a))
  b <- unname(unlist(b))
  if (!length(a) && !length(b)) return("n/a")
  if (identical(a, b)) return("ok")
  if (setequal(a, b) && length(a) == length(b)) return("order")
  "DIFF"
}
allok <- function(v) if (!length(v)) "n/a" else if (all(v == "ok")) "ok" else
  "DIFF"
prow <- function(p) {
  keep <- nzchar(p$coef) & !p$class %in% c(refused, "theta")
  sort(paste0(p$class, "/", p$coef)[keep])
}
fmt <- function(x) paste(x, collapse = " ")
t1 <- c("| # | case | brms 2.23.0 | frmtmb 0.74.0 | lane |",
        "|---|---|---|---|---|")
t2 <- c(paste("| # | case | fixef | vcov | summary | variables |",
              "default_prior | set_prior | hypothesis | draws |",
              "coef / ranef / VarCorr | conditional_effects |"),
        "|---|---|---|---|---|---|---|---|---|---|---|---|")
tally <- list()
for (i in seq_len(n)) {
  b <- readRDS(sprintf("%s/brms-%02d.rds", out, i))
  arms <- lapply(c(base = "base", lane = "lane"), function(a) {
    readRDS(sprintf("%s/frm-%s-%02d.rds", out, a, i))
  })
  fx <- vapply(arms, function(f) {
    if (!is.null(f$error)) "(error)" else fmt(f$fixef)
  }, "")
  t1 <- c(t1, sprintf("| %d | `%s` | %s | %s | %s |", i, b$id, fmt(b$fixef),
                      fx[["base"]], fx[["lane"]]))
  bp <- b$prior[nzchar(b$prior$coef), , drop = FALSE]
  okrow <- !bp$class %in% refused
  cells <- lapply(arms, function(f) {
    if (!is.null(f$error)) return(rep("ERR", 10L))
    re <- function(x) unlist(x)
    c(fixef = cmp(f$fixef, b$fixef),
      vcov = cmp(f$vcov, b$vcov),
      summary = cmp(f$summary, b$summary),
      variables = cmp(grep(P, f$variables, value = TRUE),
                      grep(P, b$variables, value = TRUE)),
      prior = cmp(prow(f$prior), prow(b$prior)),
      set_prior = allok(f$prior_ok[okrow]),
      hyp = allok(f$hyp),
      draws = cmp(grep(PD, f$draws, value = TRUE),
                  grep(PD, b$variables, value = TRUE)),
      re = {
        r <- c(cmp(re(f$coef), re(b$coef)), cmp(re(f$ranef), re(b$ranef)),
               cmp(re(f$varcorr), re(b$varcorr)))
        if (all(r == "n/a")) "n/a" else if (all(r %in% c("ok", "n/a"))) "ok"
        else if (all(r %in% c("ok", "n/a", "order"))) "order" else "DIFF"
      },
      ce = cmp(f$ce, b$ce))
  })
  for (a in names(cells)) {
    for (k in names(cells[[a]])) {
      key <- paste(a, k, cells[[a]][[k]])
      tally[[key]] <- (tally[[key]] %||% 0L) + 1L
    }
  }
  t2 <- c(t2, paste0("| ", i, " | `", b$id, "` | ",
                     paste(paste(cells$base, "/", cells$lane),
                           collapse = " | "), " |"))
}
cat("<!-- generated by dev/brmsnames-1024-table.R -->\n\n")
cat("Table 1. fixef() row names.\n\n")
cat(t1, sep = "\n")
cat("\nTable 2. Each interface against brms 2.23.0, base / lane.\n\n")
cat(t2, sep = "\n")
cat("\nTally over", n, "cases (arm interface verdict: count).\n\n")
tl <- do.call(rbind, lapply(names(tally), function(k) {
  p <- strsplit(k, " ")[[1]]
  data.frame(arm = p[1], interface = p[2], verdict = p[3], n = tally[[k]])
}))
tl <- tl[order(tl$interface, tl$arm, tl$verdict), ]
cat("| arm | interface | verdict | cases |\n|---|---|---|---|\n")
cat(sprintf("| %s | %s | %s | %d |\n", tl$arm, tl$interface, tl$verdict,
            tl$n), sep = "")
# how many cases carry the alias anywhere, per arm
alias_cases <- vapply(c("base", "lane"), function(a) {
  sum(vapply(seq_len(n), function(i) {
    f <- readRDS(sprintf("%s/frm-%s-%02d.rds", out, a, i))
    any(grepl(".frm_", unlist(f[setdiff(names(f), c("id", "frmtmb"))]),
              fixed = TRUE))
  }, NA))
}, 0L)
cat("\nCases with `.frm_` in any recorded output: base", alias_cases[["base"]],
    "of", n, ", lane", alias_cases[["lane"]], "of", n, "\n")
