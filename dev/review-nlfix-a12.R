# hurdle_cumulative + disc: brms's program with its top-category test patched from
# y == nthres + 2 to y == nthres + 1, then L1 against frm() at frm()'s estimate.
source("dev/review-nlfix-common.R")
suppressPackageStartupMessages({ library(testthat); library(rstan) })
E <- new.env(parent = asNamespace("frmtmb"))
E$`%||%` <- function(a, b) if (is.null(a)) b else a
for (f in c("dev/equiv-lib.R", "dev/equiv-specs.R", "dev/equiv-flow.R")) sys.source(f, envir = E)
d <- E$eq_dat("ordinal", seed = 4952)
set.seed(4952)
d$y <- ordered(ifelse(runif(nrow(d)) < 0.2, 0L, as.integer(d$y)), levels = 0:4)
fam <- brms::hurdle_cumulative()
run <- function(lab, fb, ff) {
  cat("\n==", lab, "\n")
  fit <- suppressWarnings(frm(ff, family = hurdle_cumulative(), data = d))
  ours <- as.numeric(logLik(fit))
  prior <- E$brms_flat_prior(fb, data = d, family = fam)
  code <- as.character(brms::make_stancode(fb, data = d, family = fam, prior = prior))
  stopifnot(grepl("y == nthres + 2", code, fixed = TRUE))
  sdat <- brms::make_standata(fb, data = d, family = fam, prior = prior)
  orig <- E$brms_stan_model(code)
  so <- suppressMessages(rstan::sampling(orig, data = sdat, chains = 0))
  pars <- E$stan_pars_from_fit(fit, sdat, code, NULL)
  r <- tryCatch(rstan::log_prob(so, rstan::unconstrain_pars(so, pars), adjust_transform = FALSE), error = function(e) paste("ERROR", substr(conditionMessage(e), 1, 120)))
  cat("brms's own program at frm()'s estimate:", r, "\n")
  patched <- sub("y == nthres + 2", "y == nthres + 1", code, fixed = TRUE)
  mp <- E$brms_stan_model(patched)
  sp <- suppressMessages(rstan::sampling(mp, data = sdat, chains = 0))
  lp <- rstan::log_prob(sp, rstan::unconstrain_pars(sp, pars), adjust_transform = FALSE)
  cat(sprintf("patched program log_prob %.10f, frm logLik %.10f, difference %.3e\n", lp, ours, lp - ours))
  s <- suppressWarnings(rstan::sampling(mp, data = sdat, chains = 1, iter = 60, refresh = 0, seed = 1))
  cat("patched program samples:", paste(dim(as.matrix(s)), collapse = "x"), "\n")
}
run("linear", brms::bf(y ~ x, disc ~ 0 + z, hu ~ z), bf(y ~ x, disc ~ 0 + z, hu ~ z))
run("body", brms::bf(y ~ b1 * x, b1 ~ 1, disc ~ 0 + z, hu ~ z, nl = TRUE), bf(y ~ b1 * x, b1 ~ 1, disc ~ 0 + z, hu ~ z, nl = TRUE))
