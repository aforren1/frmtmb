# Wall cost of run directories, from the per-pair seconds each pair's
# record carries; --record writes it into the findings between markers:
#   Rscript dev/equiv-cost.R <label>=<outdir> [...] [--record]
args <- commandArgs(trailingOnly = TRUE)
record <- "--record" %in% args
args <- setdiff(args, "--record")
out <- "<!-- generated by dev/equiv-cost.R; do not edit -->"
for (a in args) {
  lab <- sub("=.*$", "", a)
  dir <- sub("^[^=]*=", "", a)
  fs <- list.files(dir, "^p[0-9]+[.]tsv$", full.names = TRUE)
  s <- vapply(fs, function(f) as.numeric(read.delim(f)$seconds[1]), 0)
  out <- c(out, sprintf(paste0(
    "- %s (%s): %d pairs; per-pair seconds sum %.0f, median %.1f, ",
    "max %.0f (%s); %.0f minutes of work over 8 processes."),
    lab, dir, length(s), sum(s), stats::median(s), max(s),
    sub("[.]tsv$", "", basename(fs[which.max(s)])), sum(s) / 8 / 60))
}
out <- c(out, sprintf("- the compile cache holds %d programs now.",
                      length(list.files("dev/stan-cache", "[.]rds$"))))
cat(out, sep = "\n")
if (record) {
  fp <- "dev/equiv-findings.md"
  fx <- readLines(fp, warn = FALSE)
  b <- grep("^<!-- equiv-cost begin -->$", fx)
  e <- grep("^<!-- equiv-cost end -->$", fx)
  if (length(b) == 1L && length(e) == 1L && e > b) {
    writeLines(c(fx[seq_len(b)], out, fx[e:length(fx)]), fp)
  }
}
