# Puts dev/ncgp-summary.R's output in section 11 of the findings, replacing what is
# there, so the numbers in the record come from the logs.
#   Rscript dev/ncgp-summary.R > dev/ncgp-out/summary.md; Rscript dev/ncgp-gen.R
f <- "dev/ncgp-findings.md"
x <- readLines(f, warn = FALSE)
i <- grep("^## 11\\. Numbers", x)
stopifnot(length(i) == 1L)
s <- readLines("dev/ncgp-out/summary.md", warn = FALSE)
writeLines(c(x[seq_len(i)], "", "Generated by `dev/ncgp-summary.R` from the logs; long lines are logs.", "", s), f)
