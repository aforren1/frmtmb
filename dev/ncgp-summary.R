tb <- function(lines) {
  x <- grep("^NCGPT .*frm ll", lines, value = TRUE)
  m <- regmatches(x, regexec(paste0("^NCGPT (.{30}) frm ll ([-0-9.]+) sigma (\\S+) sdgp (\\S+) rho (\\S+) conv (\\d) ",
                                    "(\\S+)s \\| cf ll ([-0-9.]+) sigma (\\S+) sdgp (\\S+) rho (\\S+) \\| gap\\(frm ll - cf ll\\) (\\S+) .*warn (.*)$"), x))
  m <- do.call(rbind, m)
  data.frame(case = trimws(m[, 2]), ll = m[, 3], sigma = m[, 4], sdgp = m[, 5], conv = m[, 7],
             cf_ll = m[, 9], cf_sigma = m[, 10], cf_sdgp = m[, 11], gap = m[, 13], warn = trimws(m[, 14]))
}
L <- tb(rd(file.path(o, "truth-lane.txt")))
B <- tb(rd(file.path(o, "truth-base.txt")))
cat("| case | closed form ll, sigma, sdgp | 0.78.0 sigma, sdgp, gap | lane sigma, sdgp, gap, conv |\n|---|---|---|---|\n")
for (i in seq_len(nrow(L))) {
  j <- match(L$case[i], B$case)
  cat(sprintf("| %s | %s, %s, %s | %s, %s, %s | %s, %s, %s, %s%s |\n", L$case[i], L$cf_ll[i], L$cf_sigma[i], L$cf_sdgp[i],
              if (is.na(j)) "" else B$sigma[j], if (is.na(j)) "" else B$sdgp[j], if (is.na(j)) "" else B$gap[j],
              L$sigma[i], L$sdgp[i], L$gap[i], L$conv[i], if (L$warn[i] != "-") ", warns" else ""))
}
