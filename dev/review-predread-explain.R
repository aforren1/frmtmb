base_data <- function(seed) {
  d <- E$eq_dat("gaussian", seed = seed)
  d$off <- round(runif(nrow(d), 0, 0.5), 3)
  d$m <- sample(0:3, nrow(d), TRUE)
  d$sx <- 0.3
  d$xo <- round(d$x + rnorm(nrow(d), 0, 0.3), 3)
  d$ng <- as.integer(d$g)
  d
}
