# Lane sampleprior: the findings' prior table, generated from the two
# logs of dev/sampleprior-table.R (rellib-r9 and the lane build).
#
#   Rscript dev/sampleprior-table-md.R
#
# Writes the block between the table markers of
# dev/sampleprior-findings.md. A row is one brms 2.23.0 default that is
# not flat (brms's group and coefficient rows that inherit their class
# row are left out), with the model variants it appears in.
wt <- "C:/Users/adf44/source/r/frmtmb-wt-sampleprior"
rd <- function(f) {
  utils::read.delim(file.path(wt, "dev/sampleprior-log", f),
                    colClasses = "character", na.strings = "NA",
                    quote = "")
}
r9 <- rd("table-r9.tsv")
ln <- rd("table-lane.tsv")
key <- function(d) paste(d$family, d$variant, d$key)
# one applied verdict per model, the first row's
models_n <- function(d) length(unique(paste(d$family, d$variant)))
applied_n <- function(d) {
  a <- tapply(d$applied, paste(d$family, d$variant), `[`, 1L)
  sum(startsWith(a, "applied"))
}
stopifnot(identical(key(r9), key(ln)))
keep <- !is.na(ln$brms) & ln$brms != "(flat)" & ln$key != "(error)"
st_of <- function(s) {
  ifelse(startsWith(s, "same"), "same",
         ifelse(s == "differs" | s == "frmtmb lacks row", "DIFFERS", s))
}
tab <- data.frame(family = ln$family[keep], variant = ln$variant[keep],
                  row = ln$key[keep], brms = ln$brms[keep],
                  bounds = paste0("[", ln$brms_lb[keep], ", ",
                                  ln$brms_ub[keep], "]"),
                  r9 = ifelse(is.na(r9$frmtmb[keep]), "(none)",
                              r9$frmtmb[keep]),
                  r9_st = st_of(r9$status[keep]),
                  lane = ifelse(is.na(ln$frmtmb[keep]), "(none)",
                                ln$frmtmb[keep]),
                  lane_st = st_of(ln$status[keep]))
tab$row <- sub("[|]+$", "", tab$row)
tab$row <- gsub("[|]", " ", tab$row)
tab$row <- gsub(" +", " ", tab$row)
tab$bounds[tab$bounds == "[NA, NA]"] <- ""
tab$bounds[tab$bounds == "[, ]"] <- ""
g <- split(tab, paste(tab$family, tab$row, tab$brms, tab$r9, tab$r9_st,
                      tab$lane, tab$lane_st, sep = "\r"))
out <- do.call(rbind, lapply(g, function(z) {
  z$variant <- paste(unique(z$variant), collapse = "; ")
  z[1L, ]
}))
out <- out[order(out$family, out$row), ]
md <- c(
  "<!-- table:begin (generated by dev/sampleprior-table-md.R) -->",
  sprintf("%d brms default rows that are not flat, over %d models",
          nrow(tab), length(unique(paste(ln$family, ln$variant)))),
  sprintf("(%d families, each with its dpar variants, and %d term models);",
          length(unique(ln$family[ln$variant != "extra"])),
          length(unique(ln$family[ln$variant == "extra"]))),
  "grouped below into %d distinct lines.",
  "",
  sprintf("- rellib-r9: %d of %d rows equal brms's, %d differ.",
          sum(tab$r9_st == "same"), nrow(tab), sum(tab$r9_st == "DIFFERS")),
  sprintf("- lane: %d of %d rows equal brms's, %d differ.",
          sum(tab$lane_st == "same"), nrow(tab), sum(tab$lane_st == "DIFFERS")),
  "- applied (the defaults resolved and `prior_augmented_obj()` built from",
  "  them, each default resolving to a parameter; `apply_check()` of",
  sprintf("  dev/sampleprior-table.R): rellib-r9 %d of %d models, lane %d of %d.",
          applied_n(r9), models_n(r9), applied_n(ln), models_n(ln)),
  strwrap(sprintf("- lane, other: %s.",
          paste(sprintf("%s %d", names(table(tab$lane_st[!tab$lane_st %in%
            c("same", "DIFFERS")])), table(tab$lane_st[!tab$lane_st %in%
            c("same", "DIFFERS")])), collapse = "; ")), width = 78,
          exdent = 2),
  "",
  "| family | row (class coef group resp dpar) | brms 2.23.0 | brms [lb, ub] | rellib-r9 | lane | variants |",
  "|---|---|---|---|---|---|---|")
md[4] <- sprintf(md[4], nrow(out))
fmt <- function(v, s) ifelse(s == "same", paste0("= ", v),
                             ifelse(s == "DIFFERS", paste0("**", v, "**"),
                                    paste0(v, " (", s, ")")))
md <- c(md, sprintf("| %s | %s | %s | %s | %s | %s | %s |", out$family,
                    out$row, out$brms, out$bounds, fmt(out$r9, out$r9_st),
                    fmt(out$lane, out$lane_st), out$variant))
md <- c(md, "<!-- table:end -->")
f <- file.path(wt, "dev/sampleprior-findings.md")
s <- readLines(f)
a <- grep("^<!-- table:begin", s)
b <- grep("^<!-- table:end", s)
s <- c(s[seq_len(a - 1L)], md, s[seq(b + 1L, length.out = length(s) - b)])
writeLines(s, f)
cat("wrote", nrow(out), "lines;", nrow(tab), "rows\n")
cat(md[2:9], sep = "\n")
