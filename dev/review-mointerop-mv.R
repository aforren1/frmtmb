set.seed(3); n <- 200; x <- rnorm(n)
dmv <- data.frame(x = x, y1 = 1 + x + rnorm(n), y2 = -1 + 0.5 * x + rnorm(n))
fmv <- frm(mvbf(bf(y1 ~ x), bf(y2 ~ x)), data = dmv)
nds <- data.frame(x = c(-1, 0, 1))
show("no resp", as.data.frame(predictions(fmv, newdata = nds)))
show("fitted no resp", fitted(fmv, newdata = nds)[, "Estimate", ])
show("resp y1", as.data.frame(predictions(fmv, newdata = nds, resp = "y1"))[, c("rowid", "estimate", "std.error")])
show("avg_slopes no resp", avg_slopes(fmv, variables = "x"))
