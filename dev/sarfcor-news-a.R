prepend <- function(p, head) {
  x <- readLines(p)
  writeLines(c(head, "", x), p)
}
prepend(file.path(wt, "NEWS.md"), c(
"# frmtmb (development version)",
"",
"## New features",
"",
"- `fcor(M)`, brms's fixed residual correlation term, is supported. The",
"  residuals of a `gaussian()` or `student()` response are one draw with",
"  covariance `sigma^2 M`, or `D M D` with `D = diag(sigma)` under a",
"  predicted `sigma ~ ...`, as in brms 2.23.0. `M` comes from `data2`,",
"  covers every row of the data, and loses the rows the model drops, as",
"  in brms; a vector is its diagonal. The log-likelihood equals brms's",
"  Stan program at frmtmb's estimates to 7e-15 (gaussian) and 8e-7",
"  (student, at `nu` near 5e9), and the brms gradient there is below",
"  3e-6. A brms fit of 64 rows agrees with the maximum likelihood fit",
"  to within 0.33 standard errors in every parameter. `fitted()`,",
"  `residuals()` (pearson divides by `sigma * sqrt(diag(M))`),",
"  `simulate()`, `predict()` and `autocor_matrix()` work on the fitted",
"  rows. `newdata` is refused there, because `M` covers the fitted rows",
"  only; brms refuses it too unless `newdata2` holds a matrix over the",
"  new rows. `frm_linpred()` takes `newdata`. BREAKING: `fcor()` was",
"  refused by name before.",
"- brms 2.23.0 checks that `M` is positive definite with",
"  `min(eigen(M)$values <= 0)`, which passes a matrix with a negative",
"  eigenvalue. frmtmb refuses every `M` that is not positive definite.",
"- `sar()` is in the new residual correlation term of frmtmb.spatial.",
"  Without that package, `sar()` stops with a message that names it.",
"",
"## For extension authors",
"",
"- New seam `frmtmb_register_autocor()`. A package registers a term",
"  that correlates the residuals of a gaussian or student response, as",
"  one affine map from the response to independent innovations and its",
"  inverse. frmtmb writes the density, the mean, the draws, the",
"  residual covariance and the guards from the map. `fcor()` is",
"  frmtmb's own term of this shape, and frmtmb.spatial registers `sar()`",
"  through it. A covariance structure (`frmtmb_register_covstruct()`)",
"  cannot express such a term: it adds a latent vector to the linear",
"  predictor, and a lag SAR changes the mean of the response itself.",
"  `frmtmb_local_registries()` saves and restores the new registry."))
prepend(file.path(wt, "extensions/frmtmb.spatial/NEWS.md"), c(
"# frmtmb.spatial (development version)",
"",
"## New features",
"",
"- `sar(M, type = )`, brms's spatial simultaneous autoregressive term,",
"  in its lag and error forms, for `gaussian()` and `student()` with a",
"  constant `sigma` and `nu`, as in brms 2.23.0. It is registered",
"  through `frmtmb::frmtmb_register_autocor()`. The log-likelihood",
"  equals brms's Stan program at frmtmb's estimates, less the",
"  `-N/2 log(2 pi)` (`-N/2 log(pi)` for student) that brms leaves out,",
"  to 1.4e-14 (gaussian) and 4.4e-6 (student, at `nu` near 5e9). brms",
"  fits of 64 rows agree with the maximum likelihood fits to within",
"  0.44 standard errors in every parameter. `fitted()` reports brms's",
"  `posterior_epred()`, `(I - rho W)^-1 mu` for the lag form.",
"  `summary()` and `confint_varcorr()` report `lagsar` or `errorsar`.",
"- `rho` is estimated on `(1 / min eigenvalue, 1 / max eigenvalue)` of",
"  `M`, where `I - rho M` has a positive determinant. brms bounds it by",
"  `(min eigenvalue, max eigenvalue)`, which for a row-standardized `M`",
"  cuts off negative values below the smallest eigenvalue, and for a",
"  matrix that is not row-standardized reaches past",
"  `1 / max eigenvalue`, where brms's log-determinant is the log of a",
"  negative number.",
"- A row-standardized `M` of an irregular graph, spdep's default, has",
"  real eigenvalues that `eigen()` returns with a rounding imaginary",
"  part. brms 2.23.0 passes them to Stan as they come and its fit fails",
"  (\"variable does not exist; ... eigenMsar\"); frmtmb takes the real",
"  part when the imaginary part is below 1e-8 of the largest modulus,",
"  and refuses a matrix with complex eigenvalues.",
"- spdep's `nb` and `listw` objects are read as brms reads them",
"  (`nb2mat()` row-standardized, `listw2mat()`) without needing spdep."))
