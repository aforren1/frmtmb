source("dev/refits-lib.R")
set.seed(4)
dh <- data.frame(t = rep(1:12, 5), h = factor(rep(1:5, each = 12)),
                 x = rnorm(60), x2 = rnorm(60))
dh$y <- 1 + 0.5 * dh$x + rnorm(60)
fh <- frm(y ~ x + ar(time = t, gr = h, cov = TRUE), data = dh)
m <- frmtmb:::outer_par_map(fh)
print(data.frame(m, lab = frmtmb:::outer_par_labels(fh)))
fs <- frm(bf(y ~ x + ar(time = t, gr = h, cov = TRUE), sigma ~ x2), data = dh)
m <- frmtmb:::outer_par_map(fs)
print(data.frame(m, lab = frmtmb:::outer_par_labels(fs)))
str(fs$frame$linpreds[[2]][c("resp", "dpar", "par", "idx")])
str(fs$frame$linpreds[[1]][c("resp", "dpar", "par", "idx")])
