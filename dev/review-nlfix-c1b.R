# Fix round 1: second bodies left on a saddle, with the right starts; item 2(a); the restart's
# message. Same data seed as dev/review-nlfix-c1.R.
source("dev/review-nlfix-common.R")
ns <- asNamespace("frmtmb")
set.seed(11001)
n <- 300
d <- data.frame(x = round(rnorm(n), 3), z = round(rnorm(n), 3), g = factor(rep(1:15, each = 20)), h = factor(rep(1:12, length.out = n)))
u <- rnorm(15, 0, 0.5)
lat <- 1.5 * exp(0.6 * d$x) + 0.7 * d$z
d$yo <- ordered(cut(lat + rlogis(n), c(-Inf, 0.5, 1.5, 3, Inf), labels = 1:4))
d$yn <- 1 + 0.7 * d$x + 0.6 * d$z + rnorm(n, 0, exp(-0.5 + 0.4 * d$z))
show1 <- function(lab, r) {
  if (iserr(r)) cat(lab, ": STOP", substr(r$msg, 1, 150), "\n")
  else cat(sprintf("%s: ll=%.4f conv=%s beta=%s betad=%s\n   MSG[%s]\n   WARN[%s]\n", lab, as.numeric(logLik(r)), r$opt$convergence, paste(format(r$estimates$beta, digits = 3), collapse = ","),
                   paste(format(r$estimates$betad, digits = 3), collapse = ","), if (length(attr(r, "m"))) substr(attr(r, "m")[1], 1, 260) else "", if (length(attr(r, "w"))) substr(attr(r, "w")[1], 1, 200) else ""))
  invisible(r)
}
cat("--- gaussian: mu and sigma bodies, each a saddle\n")
fm <- bf(yn ~ 1) + nlf(mu ~ a + b1 * c1 * x) + nlf(sigma ~ exp(s0 + s1 * s2 * z)) + lf(a ~ 1) + lf(b1 ~ 1) + lf(c1 ~ 1) + lf(s0 ~ 1) + lf(s1 ~ 1) + lf(s2 ~ 1)
r0 <- show1("default start", tt(frm(fm, data = d)))
tp <- ns$par_template(fm, d)
print(names(tp$betad)); print(names(tp$beta))
st <- list(beta = c("a_(Intercept)" = 1, "b1_(Intercept)" = 1, "c1_(Intercept)" = 0.7),
           betad = setNames(c(-0.5, 0.5, 0.5), names(r0$estimates$betad)[1:3]))
r1 <- show1("all moved", tt(frm(fm, data = d, start = st)))
cat("the sigma body at the returned default fit: range", diff(range(frm_linpred(r0, dpar = "sigma"))), "\n")
cat("linear spelling mu ~ x, sigma ~ z:", as.numeric(logLik(frm(bf(yn ~ x, sigma ~ z), data = d))), "\n")
cat("\n--- mixture per location: the second component's start\n")
set.seed(11001); invisible(runif(1))
d$ymix <- ifelse(runif(n) < 0.4, -2 + 0.8 * d$x, 2 - 0.6 * d$x) + rnorm(n, 0, 0.5)
fm2 <- bf(ymix ~ 1) + nlf(mu1 ~ a1 + b1 * c1 * x) + nlf(mu2 ~ a2 + b2 * c2 * x) + lf(a1 ~ 1) + lf(b1 ~ 1) + lf(c1 ~ 1) + lf(a2 ~ 1) + lf(b2 ~ 1) + lf(c2 ~ 1)
r2 <- show1("default start", tt(frm(fm2, family = mixture(gaussian(), gaussian()), data = d)))
r3 <- show1("all moved", tt(frm(fm2, family = mixture(gaussian(), gaussian()), data = d, start = list(beta = c("a1_(Intercept)" = -1, "b1_(Intercept)" = 1, "c1_(Intercept)" = 0.5, "a2_(Intercept)" = 1, "b2_(Intercept)" = -1, "c2_(Intercept)" = 0.5)))))
cat("the second component at the default fit: range of mu2", diff(range(frm_linpred(r2, dpar = "mu2"))), " mu1", diff(range(frm_linpred(r2, dpar = "mu1"))), "\n")
cat("\n--- mu and disc\n")
fm4 <- bf(yo ~ 1) + nlf(mu ~ b1 * exp(b2 * x)) + nlf(disc ~ exp(d1 * d2 * z)) + lf(b1 ~ 1) + lf(b2 ~ 1) + lf(d1 ~ 1) + lf(d2 ~ 1)
r4 <- show1("default start", tt(frm(fm4, family = cumulative(), data = d)))
show1("all moved", tt(frm(fm4, family = cumulative(), data = d, start = list(beta = c("b1_(Intercept)" = 1, "b2_(Intercept)" = 0.5), betad = setNames(c(0.3, 0.3), names(r4$estimates$betad)[1:2])))))
cat("\n--- item 2(a): body constant at b = 0, strict local maximum there, a better maximum far off\n")
set.seed(11005)
dq <- data.frame(x = round(rnorm(n), 3))
dq$yo <- ordered(cut(-0.8 * dq$x + rlogis(n), c(-Inf, -1, 0, 1, Inf), labels = 1:4))
dq$yn <- -0.8 * dq$x + rnorm(n)
fq <- bf(yo ~ b^2 * x * (1 - b^2), b ~ 1, nl = TRUE)
r5 <- show1("cumulative, default start", tt(frm(fq, family = cumulative(), data = dq)))
show1("cumulative, start b = 1.5", tt(frm(fq, family = cumulative(), data = dq, start = list(beta = c("b_(Intercept)" = 1.5)))))
cat("thresholds only:", as.numeric(logLik(frm(yo ~ 1, family = cumulative(), data = dq))), "\n")
fg <- bf(yn ~ a + b^2 * x * (1 - b^2), a + b ~ 1, nl = TRUE)
show1("gaussian, default start", tt(frm(fg, data = dq)))
show1("gaussian, start b = 1.5", tt(frm(fg, data = dq, start = list(beta = c("b_(Intercept)" = 1.5)))))
cat("brms optimizing on the cumulative spec, 6 starts:\n")
suppressPackageStartupMessages(library(testthat))
E <- new.env(parent = ns); E$`%||%` <- function(a, b) if (is.null(a)) b else a
for (f in c("dev/equiv-lib.R", "dev/equiv-specs.R", "dev/equiv-flow.R")) sys.source(f, envir = E)
fb <- brms::bf(yo ~ b^2 * x * (1 - b^2), b ~ 1, nl = TRUE); fam <- brms::cumulative()
prior <- E$brms_flat_prior(fb, data = dq, family = fam)
code <- brms::make_stancode(fb, data = dq, family = fam, prior = prior); sdat <- brms::make_standata(fb, data = dq, family = fam, prior = prior)
m <- E$brms_stan_model(code)
print(round(sort(vapply(1:6, function(i) rstan::optimizing(m, data = sdat, seed = 100 + i, iter = 3000, as_vector = FALSE)$value, 0), decreasing = TRUE), 4))
