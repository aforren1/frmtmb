suppressPackageStartupMessages(library(frmtmb))
set.seed(514)
ds <- data.frame(x = stats::rnorm(240) * 1e-4, z = stats::rnorm(240))
ds$yb <- as.integer(ds$z > 0)
f <- suppressWarnings(frm(yb ~ z + x, family = bernoulli(), data = ds))
cat("est:", format(f$opt$par, digits = 6), "\n")
cat("vcov diag:", format(suppressWarnings(diag(vcov(f))), digits = 4), "\n")
s <- f$cache; cat("cache:", paste(ls(s), collapse = " "), "\n")
sd <- frmtmb:::fit_sdr(f)
cat("sdr names:", paste(names(sd), collapse = " "), "\n")
cat("se_lost:", paste(names(sd$se_lost), sd$se_lost, collapse = " "), "| se_null:", NCOL(sd$se_null), "\n")
