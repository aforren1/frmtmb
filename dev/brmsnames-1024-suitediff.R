## Diff of the names of every fit the core test suite makes, 0.74.0
## (rellib-r12) against the lane, from dev/brmsnames-1024-suitenames.sh.
##
##   Rscript dev/brmsnames-1024-suitediff.R [pkg] > dev/brmsnames-1024-log/suitediff.md
##
## Fits are paired by test file and call order. Every changed name must
## be accounted for by one of the lane's changes:
##   alias   the base name holds the parser's alias (.frm_<special>), and
##           the lane name is the base name without the `.frm_`;
##   prior   a coef of the prior table, where the lane name is brms's
##           rename() of the base name (brms_rename(), the lane's
##           prior_coef_brms()); "prior (row order)" where the table's
##           rows moved and, as a whole, are those renames;
##   mv-nl prefix  a brms name whose parts are the base name's in
##           another order, a_yn to yn_a (brms_lp_prefix());
## anything else is printed as UNACCOUNTED. The fixef() order changes
## touch no name and are not in this diff.
args <- commandArgs(trailingOnly = TRUE)
pkg <- if (length(args)) args[1L] else "frmtmb"
root <- "dev/brmsnames-1024-suite"
.libPaths(c("C:/Users/adf44/source/r/wt-brmsnames-lib",
            "C:/Users/adf44/source/r/rellib-r12",
            "C:/Users/adf44/AppData/Local/R/win-library/4.6"))
rn <- getFromNamespace("brms_rename", "frmtmb")
## a test file this lane adds: on base its blocks stop at their first
## failure, so its fits do not pair by call order
new_files <- c("test-brms-names-specials.rds", "test-draws-names-specials.rds")
files <- setdiff(intersect(list.files(file.path(root, "base", pkg)),
                           list.files(file.path(root, "lane", pkg))),
                 new_files)
only <- setdiff(union(list.files(file.path(root, "base", pkg)),
                      list.files(file.path(root, "lane", pkg))), files)
fields <- c("internal", "brms", "variables", "outer", "prior")
n_fit <- 0L
n_cmp <- c(internal = 0L, brms = 0L, variables = 0L, outer = 0L, prior = 0L)
changed <- list()
mismatch <- character(0)
counts_diff <- character(0)
for (fl in files) {
  b <- readRDS(file.path(root, "base", pkg, fl))
  l <- readRDS(file.path(root, "lane", pkg, fl))
  if (!identical(b$counts, l$counts)) {
    counts_diff <- c(counts_diff, sprintf("%s: base %s; lane %s", fl,
                                          b$counts, l$counts))
  }
  if (length(b$fits) != length(l$fits)) {
    mismatch <- c(mismatch, sprintf("%s: %d fits on base, %d on lane", fl,
                                    length(b$fits), length(l$fits)))
  }
  for (k in seq_len(min(length(b$fits), length(l$fits)))) {
    fb <- b$fits[[k]]
    fl2 <- l$fits[[k]]
    n_fit <- n_fit + 1L
    for (fd in fields) {
      x <- fb[[fd]]
      y <- fl2[[fd]]
      n_cmp[[fd]] <- n_cmp[[fd]] + length(x)
      if (identical(x, y)) next
      if (length(x) != length(y)) {
        changed[[length(changed) + 1L]] <- data.frame(
          file = fl, fit = k, field = fd, base = paste(x, collapse = " "),
          lane = paste(y, collapse = " "), why = "UNACCOUNTED (length)")
        next
      }
      d <- which(x != y)
      un <- gsub(".frm_", "", x[d], fixed = TRUE)
      why <- ifelse(grepl(".frm_", x[d], fixed = TRUE) & y[d] == un,
                    "alias",
             ifelse(fd == "prior" & y[d] == rn(x[d]) & un == x[d],
                    "prior",
             ifelse(fd == "prior" & y[d] == rn(un), "alias+prior",
                    "UNACCOUNTED")))
      # the prior table sorts by brms's name now, so a moved row is
      # accounted for when the rows as a whole are the renames
      if (fd == "prior" && any(why == "UNACCOUNTED") &&
          identical(sort(y), sort(rn(gsub(".frm_", "", x, fixed = TRUE))))) {
        why[why == "UNACCOUNTED"] <- "prior (row order)"
      }
      # a multivariate nonlinear parameter's prefix, a_yn to yn_a: the
      # same parts of the name in brms's order (the alias removed first)
      tok <- function(v) {
        vapply(strsplit(v, "_", fixed = TRUE),
               function(p) paste(sort(p), collapse = "_"), "")
      }
      sw <- why == "UNACCOUNTED" & fd %in% c("brms", "variables") &
        tok(un) == tok(y[d])
      why[sw] <- ifelse(grepl(".frm_", x[d][sw], fixed = TRUE),
                        "alias+mv-nl prefix", "mv-nl prefix")
      changed[[length(changed) + 1L]] <- data.frame(
        file = fl, fit = k, field = fd, base = x[d], lane = y[d], why = why)
    }
  }
}
ch <- if (length(changed)) do.call(rbind, changed) else
  data.frame(file = character(0), fit = integer(0), field = character(0),
             base = character(0), lane = character(0), why = character(0))
cat("<!-- generated by dev/brmsnames-1024-suitediff.R", pkg, "-->\n\n")
cat("Test files paired:", length(files), "\n\n")
cat("Files on one arm only:", if (length(only)) paste(only, collapse = ", ")
    else "none", "\n\n")
cat("Fits paired:", n_fit, "\n\n")
cat("Names compared, per field:",
    paste(names(n_cmp), n_cmp, sep = " ", collapse = ", "), "\n\n")
cat("Files whose fit count differs:", if (length(mismatch)) "" else "none",
    "\n")
if (length(mismatch)) cat(paste0("- ", mismatch), sep = "\n")
cat("\nFiles whose test counts differ between arms:",
    if (length(counts_diff)) "" else "none", "\n")
if (length(counts_diff)) cat(paste0("- ", counts_diff), sep = "\n")
# any alias left on the lane, in any field of any fit
left <- character(0)
for (fl in files) {
  l <- readRDS(file.path(root, "lane", pkg, fl))
  for (k in seq_along(l$fits)) {
    for (fd in fields) {
      hit <- grep(".frm_", l$fits[[k]][[fd]], fixed = TRUE, value = TRUE)
      if (length(hit)) {
        left <- c(left, sprintf("%s fit %d %s: %s", fl, k, fd,
                                paste(hit, collapse = " ")))
      }
    }
  }
}
cat("\nNames holding `.frm_` on the lane:", length(left), "\n")
if (length(left)) cat(paste0("- ", left), sep = "\n")
cat("\nChanged names:", nrow(ch), "\n\n")
if (nrow(ch)) {
  tb <- table(ch$field, ch$why)
  cat("| field |", paste(colnames(tb), collapse = " | "), "|\n")
  cat("|---|", paste(rep("---", ncol(tb)), collapse = "|"), "|\n")
  for (r in rownames(tb)) {
    cat("|", r, "|", paste(tb[r, ], collapse = " | "), "|\n")
  }
  u <- unique(ch[, c("field", "base", "lane", "why")])
  u <- u[order(u$why, u$field, u$base), ]
  cat("\nDistinct changes (", nrow(u), "), with the files they occur in:\n\n",
      sep = "")
  cat("| why | field | base | lane | files |\n|---|---|---|---|---|\n")
  for (i in seq_len(nrow(u))) {
    fs <- unique(ch$file[ch$field == u$field[i] & ch$base == u$base[i] &
                           ch$lane == u$lane[i]])
    cat(sprintf("| %s | %s | `%s` | `%s` | %s |\n", u$why[i], u$field[i],
                u$base[i], u$lane[i], paste(sub("[.]rds$", "", fs),
                                            collapse = ", ")))
  }
}
