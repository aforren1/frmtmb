# Short check, item 3, third part: coverage on new rows and fitted rows, frm()
# with theta held, brms, and an oracle at the true parameters, same datasets.
source("C:/Users/adf44/source/r/frmtmb-wt-latres/dev/review-latres-common.R")
options(warn = -1)
suppressPackageStartupMessages(library(rstan))
hel <- new.env(parent = asNamespace("frmtmb"))
hel$`%||%` <- `%||%`
sys.source("dev/equiv-lib.R", envir = hel)
s <- as.numeric(commandArgs(TRUE)[[1]])
nsets <- as.integer(commandArgs(TRUE)[[2]])
sim <- function(seed, s, ar = .4, G = 15, K = 8, b0 = .5) {
  set.seed(seed)
  d <- expand.grid(t = seq_len(K), g = factor(seq_len(G)))
  n <- nrow(d)
  d$x <- rnorm(n)
  d$e <- as.vector(replicate(G, arima.sim(list(ar = ar), K, sd = s)))
  d$y <- rpois(n, exp(b0 + .3 * d$x + d$e))
  d
}
pri <- c(brms::set_prior("student_t(3, 0, 2.5)", class = "sderr"), brms::set_prior("student_t(3, 0, 2.5)", class = "Intercept"))
fb <- brms::bf(y ~ x + ar(t, g, cov = TRUE))
fam <- brms::brmsfamily("poisson")
d0 <- sim(6001, s)
code <- brms::stancode(fb, d0, family = fam, prior = pri)
mod <- hel$brms_stan_model(code)
scaf <- brms::brm(fb, d0, family = fam, prior = pri, empty = TRUE)
res <- matrix(NA, nsets, 8, dimnames = list(NULL, c("fit_frm", "fit_brms", "new_frm", "new_brms", "new_oracle", "w_new_frm", "w_new_brms", "w_new_oracle")))
nd <- data.frame(t = 1:8, g = factor(rep("new", 8)), x = 0)
for (i in seq_len(nsets)) {
  d <- sim(6000 + i, s)
  f <- frm(y ~ x + ar(t, g, cov = TRUE), family = poisson(), data = d)
  set.seed(1)
  p <- suppressMessages(predict(f, ndraws = 800))
  pn <- suppressMessages(predict(f, newdata = nd, ndraws = 800, allow_new_levels = TRUE))
  sdat <- brms::standata(fb, d, family = fam, prior = pri)
  sf <- rstan::sampling(mod, data = sdat, chains = 2, iter = 1000, warmup = 500, seed = 11, refresh = 0)
  b <- brms::brm(fb, d, family = fam, prior = pri, empty = TRUE)
  b$fit <- sf
  b <- brms::rename_pars(b)
  o <- order(d$g, d$t)
  pb <- brms::posterior_predict(b)
  pbn <- brms::posterior_predict(b, newdata = nd, allow_new_levels = TRUE)
  set.seed(6000 + i)
  y2 <- rpois(nrow(d), exp(.5 + .3 * d$x + d$e))
  yn <- rpois(8, exp(.5 + as.numeric(arima.sim(list(ar = .4), 8, sd = s))))
  res[i, "fit_frm"] <- mean(y2 >= p[, 3] & y2 <= p[, 4])
  lo <- apply(pb, 2, quantile, .025); hi <- apply(pb, 2, quantile, .975)
  res[i, "fit_brms"] <- mean(y2[o] >= lo & y2[o] <= hi)
  res[i, "new_frm"] <- mean(yn >= pn[, 3] & yn <= pn[, 4])
  lo <- apply(pbn, 2, quantile, .025); hi <- apply(pbn, 2, quantile, .975)
  res[i, "new_brms"] <- mean(yn >= lo & yn <= hi)
  res[i, "w_new_frm"] <- mean(pn[, 4] - pn[, 3])
  res[i, "w_new_brms"] <- mean(hi - lo)
  orc <- replicate(2000, rpois(8, exp(.5 + as.numeric(arima.sim(list(ar = .4), 8, sd = s)))))
  lo <- apply(orc, 1, quantile, .025); hi <- apply(orc, 1, quantile, .975)
  res[i, "new_oracle"] <- mean(yn >= lo & yn <= hi)
  res[i, "w_new_oracle"] <- mean(hi - lo)
  if (i %% 10 == 0) cat(i, round(colMeans(res[1:i, , drop = FALSE]), 3), "\n")
}
cat("s", s, "n", nsets, "\n")
print(round(colMeans(res), 3))
