# The `||` cases of lane dblbar. Each is the text of a bf() call plus a
# family call, evaluated with brms's or frmtmb's bf() in scope, so the
# two packages read the same spelling.
dblbar_cases <- list(
  num1 = c("bf(y ~ x + (1 + x || g))", "gaussian()"),
  num2 = c("bf(y ~ x + z + (1 + x + z || g))", "gaussian()"),
  num0 = c("bf(y ~ x + (0 + x || g))", "gaussian()"),
  fac1 = c("bf(y ~ f + (1 + f || g))", "gaussian()"),
  fac0 = c("bf(y ~ f + (0 + f || g))", "gaussian()"),
  facm1 = c("bf(y ~ f + (-1 + f || g))", "gaussian()"),
  facb = c("bf(y ~ f + (f || g))", "gaussian()"),
  mix = c("bf(y ~ z + f + (1 + z + f || g))", "gaussian()"),
  inter = c("bf(y ~ x * f + (1 + x * f || g))", "gaussian()"),
  inter2 = c("bf(y ~ x + f:x + (1 + f:x || g))", "gaussian()"),
  ipoly = c("bf(y ~ poly(x, 2) + (1 + poly(x, 2) || g))", "gaussian()"),
  iI = c("bf(y ~ x + I(x^2) + (1 + I(x^2) || g))", "gaussian()"),
  grby = c("bf(y ~ x + (1 + x || gr(g, by = hg)))", "gaussian()"),
  grbyf = c("bf(y ~ f + (1 + f || gr(g, by = hg)))", "gaussian()"),
  grcor = c("bf(y ~ f + (1 + f || gr(g, cor = TRUE)))", "gaussian()"),
  cross = c("bf(y ~ x + (1 + x || g1:g2))", "gaussian()"),
  crossf = c("bf(y ~ f + (1 + f || g1:g2))", "gaussian()"),
  nest = c("bf(y ~ x + (1 + x || g1/g2))", "gaussian()"),
  nestf = c("bf(y ~ f + (1 + f || g1/g2))", "gaussian()"),
  mm = c("bf(y ~ x + (1 + x || mm(m1, m2)))", "gaussian()"),
  mmf = c("bf(y ~ f + (1 + f || mm(m1, m2)))", "gaussian()"),
  idmix = c("bf(y ~ x + f + (1 + x | p | g) + (1 + f || g1))",
            "gaussian()"),
  idgr = c(paste0("bf(y ~ x + (1 + x || gr(g, id = 'p')), ",
                  "sigma ~ (1 | gr(g, id = 'p')))"), "gaussian()"),
  idbar = c("bf(y ~ x + (1 + x || p | g))", "gaussian()"),
  sigma = c("bf(y ~ x + (1 | g1), sigma ~ (1 + f || g))", "gaussian()"),
  sigman = c("bf(y ~ x + (1 | g1), sigma ~ (1 + x || g))", "gaussian()"),
  nl = c(paste0("bf(y ~ a + b * x, a ~ 1 + (1 + f || g), b ~ 1, ",
                "nl = TRUE)"), "gaussian()"),
  mo1 = c("bf(y ~ mo(xo) + (1 + mo(xo) || g))", "gaussian()"),
  mof = c("bf(y ~ mo(xo) * f + (mo(xo) * f || g))", "gaussian()"),
  cs1 = c("bf(yo ~ x + (cs(1) || g))", "acat()"),
  csx = c("bf(yo ~ x + (cs(1 + x) || g))", "acat()"),
  dup = c("bf(y ~ f + (1 + f || g) + (1 | g))", "gaussian()"),
  twin = c("bf(y ~ f + (1 + f || g) + (1 + f || g))", "gaussian()"),
  cmc = c("bf(y ~ 0 + f + (0 + f || g), cmc = FALSE)", "gaussian()"),
  mv = c(paste0("mvbf(bf(y ~ f + (1 + f || g)), ",
                "bf(z ~ x + (1 + x || g)), rescor = FALSE)"), "gaussian()")
)
