set_libs("after")
suppressPackageStartupMessages(library(frmtmb))
set.seed(1)
g <- factor(rep(seq_len(25L), each = 8))
z <- rnorm(200)
b <- rnorm(25, 0, 0.3)
y <- rpois(200, exp(0.5 + 0.3 * z + rnorm(25, 0, 0.6)[g] + b[g] * z))
d <- data.frame(y, g, w = 2000 + 5 * z)
m <- tryCatch(frm(bf(y ~ w + (1 + w | g)), family = poisson(), data = d, importance = 300L), error = conditionMessage)
cat(if (is.character(m)) m else "fit", "\n")
l <- suppressWarnings(frm(bf(y ~ w + (1 + w | g)), family = poisson(), data = d))
print(l$opt$par); print(l$opt$convergence); cat(as.numeric(logLik(l)), "\n")
print(frmtmb:::varcorr_matrices(l)[[1]])
# plan$u against the closure's own draws at the anchor, on this ill-conditioned H
ns <- asNamespace("frmtmb")
fr <- frm(bf(y ~ w + (1 + w | g)), family = poisson(), data = d, dry_run = "frame")
nll <- ns$build_objective(fr)
tpl <- ns$make_start(fr, NULL, NULL)
lap <- RTMB::MakeADFun(nll, tpl, random = "b", map = fr[["map"]], silent = TRUE)
lay <- ns$imp_layout(fr[["re_blocks"]])
at <- setNames(l$opt$par, names(lap$par))
plan <- ns$imp_plan(lap, fr, lay, at, 300L, 1L)
io <- ns$build_importance_objective(fr, lay, ns$imp_group_map(fr, lay), plan)
pr <- environment(io$fn)$proposal(ns$imp_par_list(tpl, at, fr[["map"]]))
ng <- plan$n_group
nd <- plan$n_draw
dif <- vapply(seq_len(plan$q), function(j) {
  max(abs(as.numeric(pr$u[[j]]) - as.vector(plan$u[plan$idx[j, ], , drop = FALSE])))
}, 0)
cat("max |closure u - plan u| by coordinate:", format(dif, digits = 3), "\n")
cat("max scale of plan u:", format(apply(plan$u[plan$idx[1, ], , drop = FALSE], 1, max)[1:2], digits = 3), "\n")
cat("max |closure logdet - plan logdet|:", max(abs(as.numeric(pr$logdet) - plan$logdet_l)), "\n")
cat("kappa of H, first group:", kappa(plan$hlik[, , 1] + plan$prec, exact = TRUE), "\n")
