# What brms 2.23.0 does for its simplex-response families: stancode,
# standata, validation, default priors. Output: dev/famsimplex-brms-probe.log
.libPaths(c("C:/Users/adf44/AppData/Local/R/win-library/4.6"))
suppressPackageStartupMessages(library(brms))
cat("brms", format(packageVersion("brms")), "\n")
set.seed(1)
n <- 50
dd <- data.frame(x = rnorm(n), z = rnorm(n), g = gl(5, 10))
G <- matrix(rgamma(n * 3, 2), n, 3)
Y <- G / rowSums(G)
colnames(Y) <- c("a", "b", "c")
dd$Y <- Y
dd$y1 <- Y[, 1]; dd$y2 <- Y[, 2]; dd$y3 <- Y[, 3]
sec <- function(t) cat("\n========", t, "========\n")
try_show <- function(expr) {
  r <- tryCatch(expr, error = function(e) paste("ERROR:", conditionMessage(e)),
                warning = function(w) paste("WARNING:", conditionMessage(w)))
  print(r)
}
sec("families")
print(str(dirichlet()))
print(tryCatch(str(brms::dirichlet2()), error = function(e) conditionMessage(e)))
print(str(logistic_normal()))
print(args(dirichlet)); print(args(logistic_normal))
print(tryCatch(args(brms::dirichlet2), error = function(e) conditionMessage(e)))
sec("dirichlet cbind stancode")
try_show(stancode(bf(cbind(y1, y2, y3) ~ x), data = dd, family = dirichlet()))
sec("dirichlet matrix-column stancode")
cat(stancode(bf(Y ~ x), data = dd, family = dirichlet()))
sec("dirichlet standata names")
sd1 <- standata(bf(Y ~ x), data = dd, family = dirichlet())
print(names(sd1)); print(head(sd1$Y)); print(sd1$ncat)
sec("dirichlet phi formula, mub formula, RE")
cat(stancode(bf(Y ~ x + (1 | ID | g), phi ~ z, muc ~ z), data = dd,
             family = dirichlet()))
sec("dirichlet default priors")
print(default_prior(bf(Y ~ x + (1 | ID | g), phi ~ z), data = dd,
                    family = dirichlet()))
print(default_prior(bf(Y ~ x), data = dd, family = dirichlet()))
sec("dirichlet refcat")
cat(stancode(bf(Y ~ x), data = dd, family = dirichlet(refcat = "b")))
try_show(stancode(bf(Y ~ x), data = dd, family = dirichlet(refcat = NA)))
sec("dirichlet links")
print(dirichlet()$link); print(dirichlet()$link_phi)
try_show(dirichlet(link = "probit"))
try_show(dirichlet(link_phi = "identity"))
sec("validation")
bad <- dd; bad$Y[1, ] <- c(0.5, 0.5, 0.1)
try_show(standata(bf(Y ~ x), data = bad, family = dirichlet()))
bad$Y[1, ] <- c(0.5, 0.5, 1e-11)
try_show(standata(bf(Y ~ x), data = bad, family = dirichlet()))
bad$Y[1, ] <- c(0.5, 0.5, 1e-9)
try_show(standata(bf(Y ~ x), data = bad, family = dirichlet()))
bad$Y[1, ] <- c(0.5, 0.5, 0)
try_show(standata(bf(Y ~ x), data = bad, family = dirichlet()))
bad$Y[1, ] <- c(1.2, -0.2, 0)
try_show(standata(bf(Y ~ x), data = bad, family = dirichlet()))
bad$Y[1, ] <- c(NA, 0.5, 0.5)
try_show(standata(bf(Y ~ x), data = bad, family = dirichlet()))
nonames <- dd; nonames$Y <- unname(Y)
try_show(standata(bf(Y ~ x), data = nonames, family = dirichlet()))
cat(try(stancode(bf(Y ~ x), data = nonames, family = dirichlet())), "\n")
two <- dd; two$Y <- Y[, 1:2] / rowSums(Y[, 1:2])
try_show(standata(bf(Y ~ x), data = two, family = dirichlet()))
one <- dd; one$Y <- Y[, 1, drop = FALSE]
try_show(standata(bf(Y ~ x), data = one, family = dirichlet()))
vec <- dd
try_show(standata(bf(y1 ~ x), data = vec, family = dirichlet()))
sec("dirichlet2")
d2 <- tryCatch(brms::dirichlet2(), error = function(e) NULL)
if (!is.null(d2)) {
  cat(stancode(bf(Y ~ x), data = dd, family = dirichlet2()))
  cat(stancode(bf(Y ~ x, mua ~ 1), data = dd, family = dirichlet2()))
  print(default_prior(bf(Y ~ x), data = dd, family = dirichlet2()))
}
sec("logistic_normal stancode")
cat(stancode(bf(Y ~ x), data = dd, family = logistic_normal()))
sec("logistic_normal sigma, lncor, RE")
cat(stancode(bf(Y ~ x + (1 | ID | g), sigmab ~ z, muc ~ z), data = dd,
             family = logistic_normal()))
sec("logistic_normal default priors")
print(default_prior(bf(Y ~ x), data = dd, family = logistic_normal()))
print(default_prior(bf(Y ~ x + (1 | g), sigmac ~ z), data = dd,
                    family = logistic_normal()))
sec("logistic_normal refcat")
cat(stancode(bf(Y ~ x), data = dd, family = logistic_normal(refcat = "c")))
sec("logistic_normal validation: zero")
bad <- dd; bad$Y[1, ] <- c(0.5, 0.5, 0)
try_show(standata(bf(Y ~ x), data = bad, family = logistic_normal()))
sec("lncor as formula")
try_show(stancode(bf(Y ~ x, lncor ~ z), data = dd, family = logistic_normal()))
sec("standata logistic_normal")
sd2 <- standata(bf(Y ~ x), data = dd, family = logistic_normal())
print(names(sd2)); print(sd2$ncat); print(sd2$nlncor)
sec("functions block helper")
print(brms:::valid_dpars(dirichlet()))
print(brms:::valid_dpars(logistic_normal(), bf(Y ~ x)))
