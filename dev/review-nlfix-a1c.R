x <- tt(confint(b, parm = "x", method = "profile")); show("profile lin", if (iserr(x)) x else as.numeric(x))
x <- tt(drop1(a)); show("drop1", if (iserr(x)) x else 1)
x <- tt(anova(a, b)); show("anova nl lin", if (iserr(x)) x else 1)
