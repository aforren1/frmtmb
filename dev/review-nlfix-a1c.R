`%||%` <- function(a, b) if (is.null(a)) b else a
set.seed(4103)
n <- 300
d <- data.frame(x = rnorm(n), z = rnorm(n), g = factor(rep(1:15, each = 20)), w = runif(n, 0.5, 2))
d$y <- cut(0.8 * d$x + rlogis(n), c(-Inf, -1, 0, 1, Inf), labels = 1:4, ordered_result = TRUE)
d$yh <- ordered(ifelse(runif(n) < 0.2, 0L, as.integer(d$y)), levels = 0:4)
nd <- d[1:7, ]; nd$x <- nd$x + 1
dmax <- function(a, b) { if (iserr(a)) return(paste("nl ERR", substr(a$msg, 1, 200))); if (iserr(b)) return(paste("lin ERR", substr(b$msg, 1, 200))); a <- as.numeric(unlist(a)); b <- as.numeric(unlist(b)); if (length(a) != length(b)) return(paste("lengths", length(a), length(b))); sprintf("max diff %.3e, NA in nl %d, in lin %d", max(abs(a - b), na.rm = TRUE), sum(is.na(a)), sum(is.na(b))) }
pair <- function(lab, fnl, flin, ...) {
  cat("\n---", lab, "\n")
  a <- tt(do.call(frm, c(list(fnl), list(...)))); b <- tt(do.call(frm, c(list(flin), list(...))))
  if (iserr(a) || iserr(b)) { cat(" nl:", if (iserr(a)) a$msg else "ok", "\n lin:", if (iserr(b)) b$msg else "ok", "\n"); return(invisible()) }
  cat(" logLik", as.numeric(logLik(a)), as.numeric(logLik(b)), "\n")
  cat(" fitted       ", dmax(tt(fitted(a)), tt(fitted(b))), "\n")
  cat(" fitted nd    ", dmax(tt(fitted(a, newdata = nd)), tt(fitted(b, newdata = nd))), "\n")
  cat(" linpred nd   ", dmax(tt(frm_linpred(a, newdata = nd)), tt(frm_linpred(b, newdata = nd))), "\n")
  cat(" predict nd   ", dmax(tt({ set.seed(3); predict(a, newdata = nd) }), tt({ set.seed(3); predict(b, newdata = nd) })), "\n")
  cat(" simulate     ", dmax(tt({ set.seed(4); as.numeric(unlist(lapply(simulate(a, nsim = 3), as.integer))) }), tt({ set.seed(4); as.numeric(unlist(lapply(simulate(b, nsim = 3), as.integer))) })), "\n")
  cat(" osa          ", dmax(tt({ set.seed(5); residuals(a, type = "osa") }), tt({ set.seed(5); residuals(b, type = "osa") })), "\n")
  cat(" update       ", dmax(tt(as.numeric(logLik(update(a, data = d[1:220, ])))), tt(as.numeric(logLik(update(b, data = d[1:220, ]))))), "\n")
  invisible(list(a, b))
}
pair("hurdle_cumulative", bf(yh ~ b1 * x, b1 ~ 1, hu ~ z, nl = TRUE), bf(yh ~ 0 + x, hu ~ z), family = hurdle_cumulative(), data = d)
pair("hurdle_cumulative disc", bf(yh ~ b1 * x, b1 ~ 1, hu ~ z, disc ~ 0 + z, nl = TRUE), bf(yh ~ 0 + x, hu ~ z, disc ~ 0 + z), family = hurdle_cumulative(), data = d)
pair("cumulative disc", bf(y ~ b1 * x, b1 ~ 1, disc ~ 0 + z, nl = TRUE), bf(y ~ 0 + x, disc ~ 0 + z), family = cumulative(), data = d)
pair("sratio disc", bf(y ~ b1 * x, b1 ~ 1, disc ~ 0 + z, nl = TRUE), bf(y ~ 0 + x, disc ~ 0 + z), family = sratio(), data = d)
pair("ordinal mixture", bf(y ~ b1 * x, b1 ~ 1, nl = TRUE), bf(y ~ 0 + x), family = mixture(cumulative(), cumulative()), data = d)
pair("weights", bf(y | weights(w) ~ b1 * x, b1 ~ 1, nl = TRUE), bf(y | weights(w) ~ 0 + x), family = cumulative(), data = d)
pair("nlf chain", bf(y ~ eta) + nlf(eta ~ b1 * x) + lf(b1 ~ 1), bf(y ~ 0 + x), family = cumulative(), data = d)
pair("nlf disc body", bf(y ~ 0 + x) + nlf(disc ~ exp(a * z)) + lf(a ~ 1), bf(y ~ 0 + x, disc ~ 0 + z), family = cumulative(), data = d)
dna <- d; dna$x[c(3, 50)] <- NA
a <- tt(frm(bf(y ~ b1 * x, b1 ~ 1, nl = TRUE), family = cumulative(), data = dna, na.action = na.exclude))
b <- tt(frm(y ~ 0 + x, family = cumulative(), data = dna, na.action = na.exclude))
cat("\n--- na.exclude:", dmax(tt(frm_linpred(a)), tt(frm_linpred(b))), "| fitted", dmax(tt(fitted(a)), tt(fitted(b))), "\n")
