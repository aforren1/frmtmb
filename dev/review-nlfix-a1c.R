  x <- tt(loo(sa)); show("loo", if (iserr(x)) x else x$estimates[1, 1])
  x <- tt(conditional_effects(sa, effects = "x")); show("cond eff", if (iserr(x)) x else nrow(x[[1]]))
  x <- tt(hypothesis(sa, "b1_Intercept > 0")); show("hypothesis", if (iserr(x)) x else x$hypothesis$Estimate)
  print(prior_summary(sa))
