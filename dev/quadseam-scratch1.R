f <- frm(bf(y ~ x + (1 | g)), family = bernoulli(), data = d1, quadrature = TRUE)
print(rownames(vcov(f)))
print(outer_par_names <- frmtmb:::outer_par_names(f))
print(f$opt$par)
print(diag(vcov(f)))
print(f$cache$sdr$se_lost)
sdr <- frmtmb:::sdr_of(f); print(sdr$cov.fixed); print(sdr$se_lost)
print(summary(f))
