# the ported ledger, before and after
led <- function(f, label) {
  if (!file.exists(f)) return(cat(sprintf("%-8s MISSING\n", label)))
  x <- readLines(f, warn = FALSE)
  tot <- grep("^\\| \\*\\*total\\*\\*", x, value = TRUE)[1L]
  cat(sprintf("%-8s %s\n", label, trimws(tot)))
}
