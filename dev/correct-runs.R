tier <- function(file, label) {
  if (!file.exists(file)) {
    cat(sprintf("%-8s MISSING %s\n", label, file))
    return(invisible(NULL))
  }
  x <- readLines(file, warn = FALSE)
  r <- grep("^RESULT ", x, value = TRUE)
  num <- function(key) {
    v <- regmatches(r, regexpr(paste0(key, "=[0-9]+"), r))
    sum(as.integer(sub(".*=", "", v)))
  }
  ran <- grep("^(SUITE|GATED) ran ", x, value = TRUE)
  bad <- grep("NO RESULT LINE", x, value = TRUE)
  cat(sprintf("%-8s files %d  pass %d  fail %d  error %d  skip %d  %s\n",
              label, length(r), num("pass"), num("fail"), num("err"),
              num("skip"),
              if (length(ran)) ran[length(ran)] else "no ran line"))
  if (length(bad)) cat("  ", length(bad), "files produced no RESULT\n")
  invisible(NULL)
}

